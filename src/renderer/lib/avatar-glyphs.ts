export const getAvatarGlyph = (id: string) => {
  if (!id) return AVATAR_GLYPHS[0];
  let hash = 0;
  for (let i = 0; i < id.length; i++) {
    hash = id.charCodeAt(i) + ((hash << 5) - hash);
  }
  return AVATAR_GLYPHS[Math.abs(hash) % AVATAR_GLYPHS.length];
};
